import { describe, expect, it } from "vitest";
import { ROOT, run, tempFile } from "./helpers.js";

const script = `${ROOT}/scripts/release/verify-attribution.sh`;
const check = (message: string) => run(script, [tempFile("COMMIT_EDITMSG", message)]).status;

describe("verify-attribution.sh", () => {
  it.each([
    "feat(core): port the tokenizer",
    "fix: handle ZWNJ\n\nCo-Authored-By: Dolan H. <0xdolan@gmail.com>",
    "docs: explain how Claude rules are documented",
    "chore: mention the word generated with care",
  ])("accepts %j", (message) => {
    expect(check(message)).toBe(0);
  });

  it.each([
    "feat: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>",
    "feat: x\n\nco-authored-by: Claude Opus 5.5 <claude@example.com>",
    "feat: x\n\nCo-authored-by: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>",
    "feat: x\n\nCo-authored-by: renovate <bot@renovateapp.com>",
    "feat: x\n\nCo-authored-by: github-actions <41898282+github-actions[bot]@users.noreply.github.com>",
    "feat: x\n\nGenerated with [Claude Code](https://claude.com/claude-code)",
    "feat: x\n\nGenerated by AI",
    "feat: x\n\nThanks <noreply@anthropic.com>",
  ])("rejects %j", (message) => {
    expect(check(message)).toBe(1);
  });

  it("ignores comment lines that git drops", () => {
    expect(check("fix: y\n# Co-Authored-By: Claude <noreply@anthropic.com>\n")).toBe(0);
  });

  it("needs exactly one argument", () => {
    expect(run(script, []).status).toBe(2);
  });
});
