/**
 * Write packages/config/tokens.css (Tailwind v4 and shadcn variables) from tokens.ts.
 *
 *   tsx scripts/brand/make-tokens.ts           write the file (or: make tokens)
 *   tsx scripts/brand/make-tokens.ts --check   fail if the file is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { brand, fonts, motion, shape, themes, underlines } from "@zimanyar/config/tokens";

const variables = (colors: Record<string, string>) =>
  Object.entries(colors).map(([name, value]) => `  --${name}: ${value};`);

const darkBlock = variables(themes.dark).map((line) => `  ${line}`);

export function renderCss(): string {
  return [
    "/* Generated by scripts/brand/make-tokens.ts from tokens.ts. Do not edit. */",
    "",
    ":root {",
    ...variables(themes.light),
    ...Object.entries(brand).map(([name, value]) => `  --brand-${name}: ${value};`),
    `  --radius: ${shape.radius};`,
    `  --measure: ${shape.measure};`,
    `  --leading-latin: ${shape.leadingLatin};`,
    `  --leading-arabic: ${shape.leadingArabic};`,
    `  --scale-arabic: ${shape.scaleArabic};`,
    `  --duration-fast: ${motion.fast};`,
    `  --duration-normal: ${motion.normal};`,
    `  --easing-standard: ${motion.easing};`,
    "}",
    "",
    "/* Dark follows the system unless the interface sets a theme itself. */",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    ...darkBlock,
    "  }",
    "}",
    "",
    ':root[data-theme="dark"] {',
    ...variables(themes.dark),
    "}",
    "",
    "@media (prefers-reduced-motion: reduce) {",
    "  :root {",
    "    --duration-fast: 0ms;",
    "    --duration-normal: 0ms;",
    "  }",
    "}",
    "",
    "@theme inline {",
    ...Object.keys(themes.light).map((name) => `  --color-${name}: var(--${name});`),
    ...Object.keys(brand).map((name) => `  --color-brand-${name}: var(--brand-${name});`),
    `  --font-sans: ${fonts.latin};`,
    `  --font-arabic: ${fonts.arabic};`,
    `  --font-mono: ${fonts.mono};`,
    "  --radius-sm: calc(var(--radius) - 0.125rem);",
    "  --radius-md: var(--radius);",
    "  --radius-lg: calc(var(--radius) + 0.25rem);",
    "}",
    "",
    "/* Finding underlines: the shape differs as well as the colour. */",
    ...Object.entries(underlines).flatMap(([name, { color, style }]) => [
      `.underline-${name} {`,
      "  text-decoration-line: underline;",
      `  text-decoration-style: ${style};`,
      `  text-decoration-color: var(--${color});`,
      "  text-decoration-thickness: 2px;",
      "  text-underline-offset: 0.2em;",
      "}",
    ]),
    "",
  ].join("\n");
}

export function main(args: readonly string[]): number {
  const target = resolve(dirname(fileURLToPath(import.meta.url)), "../../packages/config/tokens.css");
  if (!args.includes("--check")) {
    writeFileSync(target, renderCss());
    return 0;
  }
  if (readFileSync(target, "utf8") === renderCss()) return 0;
  console.error("packages/config/tokens.css is out of date; run make tokens");
  return 1;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
