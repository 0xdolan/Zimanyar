/**
 * Compile every rule's metadata into packages/rules/src/generated/catalogue.ts, so that the rules run
 * in a worker with no file access. Fails on metadata that is incomplete or links to a missing lesson.
 *
 *   pnpm exec tsx scripts/content/generate-rule-catalogue.ts           (or: make rules)
 *   pnpm exec tsx scripts/content/generate-rule-catalogue.ts --check
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SRC = resolve(ROOT, "packages/rules/src");
const TARGET = resolve(SRC, "generated/catalogue.ts");
const CATEGORIES = new Set([
  "orthography",
  "spelling",
  "morphology",
  "agreement",
  "syntax",
  "punctuation",
  "style",
]);
const SEVERITIES = new Set(["error", "warning", "hint"]);
const UI_LANGS = ["en", "ckb", "kmr"] as const;

interface LessonInput {
  lang: string;
  lessonId: number;
  anchor?: string;
}
type LessonIndex = Record<string, Record<string, { title: string; anchors: string[] }>>;

export function validateMeta(meta: Record<string, unknown>, where: string, lessons: LessonIndex): string[] {
  const problems: string[] = [];
  const fail = (text: string) => problems.push(`${where}: ${text}`);
  const id = meta["id"];
  if (typeof id !== "string" || !/^(ckb|kmr|any)\.[a-z]+\.[a-z-]+$/.test(id)) fail("bad id");
  if (!CATEGORIES.has(meta["category"] as string)) fail("bad category");
  if (!SEVERITIES.has(meta["severity"] as string)) fail("bad severity");
  const confidence = meta["confidence"];
  if (typeof confidence !== "number" || confidence < 0 || confidence > 1) fail("bad confidence");
  if (typeof meta["safeFix"] !== "boolean") fail("safeFix must be true or false");
  for (const part of ["message", "reason"]) {
    const texts = meta[part] as Record<string, unknown> | undefined;
    for (const lang of UI_LANGS) {
      if (typeof texts?.[lang] !== "string" || texts[lang] === "") fail(`${part} needs ${lang}`);
    }
  }
  const examples = meta["examples"];
  if (!Array.isArray(examples) || examples.length < 2) fail("needs at least two examples");
  const links = (meta["lessons"] ?? []) as LessonInput[];
  if (links.length === 0) fail("needs a lesson link");
  for (const link of links) {
    const lesson = lessons[link.lang]?.[String(link.lessonId)];
    if (lesson === undefined) fail(`no lesson ${link.lang} ${link.lessonId}`);
    else if (link.anchor !== undefined && !lesson.anchors.includes(link.anchor)) {
      fail(`no anchor ${link.anchor} in lesson ${link.lang} ${link.lessonId}`);
    }
  }
  return problems;
}

export function render(): string {
  const lessons = JSON.parse(
    readFileSync(resolve(ROOT, "packages/rules/lessons.json"), "utf8"),
  ) as LessonIndex;
  const files = (readdirSync(SRC, { recursive: true }) as string[])
    .filter((file) => file.endsWith(".meta.yaml"))
    .sort();
  const problems: string[] = [];
  const catalogue = files.map((file) => {
    const meta = parse(readFileSync(join(SRC, file), "utf8")) as Record<string, unknown>;
    problems.push(...validateMeta(meta, relative(ROOT, join(SRC, file)), lessons));
    const links = (meta["lessons"] ?? []) as LessonInput[];
    return {
      id: meta["id"],
      lang: String(meta["id"]).split(".")[0],
      family: meta["family"],
      category: meta["category"],
      severity: meta["severity"],
      confidence: meta["confidence"],
      safeFix: meta["safeFix"],
      standardOnly: meta["standardOnly"] === true,
      notice: meta["notice"] === true,
      message: meta["message"],
      reason: meta["reason"],
      examples: meta["examples"],
      lessons: links.map((link) => ({
        lang: link.lang,
        lessonId: link.lessonId,
        anchor: link.anchor ?? "",
        title: lessons[link.lang]?.[String(link.lessonId)]?.title ?? "",
      })),
    };
  });
  if (problems.length > 0) throw new Error(problems.join("\n"));
  return `// Generated by scripts/content/generate-rule-catalogue.ts from the rules' metadata. Do not edit.\n\nexport const CATALOGUE = ${JSON.stringify(catalogue, null, 2)};\n`;
}

export function main(args: readonly string[]): number {
  const text = render();
  if (!args.includes("--check")) {
    writeFileSync(TARGET, text);
    return 0;
  }
  if (readFileSync(TARGET, "utf8") === text) return 0;
  console.error("the rule catalogue is out of date; run make rules");
  return 1;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
